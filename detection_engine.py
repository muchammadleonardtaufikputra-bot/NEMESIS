
"""
NEMESIS CORE
Defensive Event Detection Engine

Analyzes inert simulation events against local,
predefined defensive detection rules.
"""

from datetime import datetime, timezone


DETECTION_RULES = {
    "AUTH-001": {
        "rule_id": "DET-AUTH-001",
        "rule_name": "Authentication Failure Detection",
        "expected_category": "Authentication",
        "expected_severity": "MEDIUM",
        "description": (
            "Detects a simulated authentication failure event."
        ),
        "recommendation": (
            "Review authentication logs and account protection settings."
        ),
    },
    "FW-001": {
        "rule_id": "DET-FW-001",
        "rule_name": "Firewall Alert Detection",
        "expected_category": "Network Security",
        "expected_severity": "HIGH",
        "description": (
            "Detects a simulated firewall configuration alert."
        ),
        "recommendation": (
            "Review firewall profiles and approved security policies."
        ),
    },
    "EDR-001": {
        "rule_id": "DET-EDR-001",
        "rule_name": "Unusual Process Alert Detection",
        "expected_category": "Endpoint Security",
        "expected_severity": "MEDIUM",
        "description": (
            "Detects a simulated unusual process alert."
        ),
        "recommendation": (
            "Review endpoint security alerts and approved applications."
        ),
    },
    "ACCESS-001": {
        "rule_id": "DET-ACCESS-001",
        "rule_name": "Privilege Change Detection",
        "expected_category": "Access Control",
        "expected_severity": "HIGH",
        "description": (
            "Detects a simulated privilege change event."
        ),
        "recommendation": (
            "Review authorized account privileges and access policies."
        ),
    },
}


def get_detection_rules():
    """Return a safe summary of available detection rules."""

    return {
        event_code: {
            "rule_id": rule["rule_id"],
            "rule_name": rule["rule_name"],
            "expected_category": rule["expected_category"],
            "expected_severity": rule["expected_severity"],
        }
        for event_code, rule in DETECTION_RULES.items()
    }


def analyze_event(event):
    """
    Analyze one event generated by the inert simulation engine.

    This function does not inspect the operating system,
    execute commands, or access external systems.
    """

    if not isinstance(event, dict):
        raise ValueError("Event must be a dictionary.")

    if event.get("status") != "SIMULATED":
        raise ValueError("Only simulated events can be analyzed.")

    if event.get("execution_mode") != "INERT_LOCAL_EVENT":
        raise ValueError("Unsupported event execution mode.")

    event_code = event.get("event_code")

    if not isinstance(event_code, str):
        raise ValueError("Invalid event code.")

    rule = DETECTION_RULES.get(event_code)

    if rule is None:
        return {
            "detection_id": None,
            "status": "NOT_DETECTED",
            "event_code": event_code,
            "matched_rule": None,
            "message": "No matching defensive detection rule.",
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }

    category_matches = (
        event.get("category") == rule["expected_category"]
    )

    severity_matches = (
        event.get("severity") == rule["expected_severity"]
    )

    if not category_matches or not severity_matches:
        return {
            "detection_id": None,
            "status": "NOT_DETECTED",
            "event_code": event_code,
            "matched_rule": None,
            "message": "Event attributes did not match the detection rule.",
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }

    return {
        "detection_id": rule["rule_id"],
        "status": "DETECTED",
        "event_code": event_code,
        "matched_rule": rule["rule_name"],
        "severity": rule["expected_severity"],
        "description": rule["description"],
        "recommendation": rule["recommendation"],
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }
